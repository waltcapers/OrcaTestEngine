package orca.engine.util

/**
 * Abstraction layer for sleep operations.
 *
 * The OrcaEngine uses this interface instead of Thread.sleep()
 * so that unit tests can replace the delay behavior with a fake
 * implementation that records requested sleeps without blocking.
 */
interface SleepProvider {
    /** Sleep for the specified number of milliseconds. */
    fun sleep(ms: Long)
}

/** Default implementation that simply delegates to Thread.sleep(). */
object DefaultSleepProvider : SleepProvider {
    override fun sleep(ms: Long) = Thread.sleep(ms)
}
